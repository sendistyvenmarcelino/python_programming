places = ["Tokyo", "Madrid", "Paris", "London", "Manchester"]
print("1. Asli:", places)
print("2. Alfabetis (sorted):", sorted(places))
print("3. Asli:", places)
print("4. Terbalik (sorted):", sorted(places, reverse=True))
print("5. Asli:", places)
places.reverse()
print("6. Urutan dibalik:", places)
places.reverse()
print("7. Kembali semula:", places)
places.sort()
print("8. Urut permanen A-Z:", places)
places.sort(reverse=True)
print("9. Urut permanen Z-A:", places)