football_clubs = ["Real Madrid", "Barcelona", "Liverpool", "Bayern Munich"]
print("List awal klub:", football_clubs)
football_clubs.append("Manchester City")
print("Setelah append():", football_clubs)
football_clubs.insert(1, "Juventus")
print("Setelah insert():", football_clubs)
del football_clubs[2]
print("Setelah del:", football_clubs)
popped_club = football_clubs.pop()
print(f"Klub yang di-pop (dihapus): {popped_club}")
print("Setelah pop():", football_clubs)
football_clubs.remove("Liverpool")
print("Setelah remove():", football_clubs)
print("Urutan sementara (sorted):", sorted(football_clubs))
print("List tetap aman tidak berubah permanen:", football_clubs)
football_clubs.reverse()
print("Setelah reverse():", football_clubs)
football_clubs.sort()
print("Setelah sort() permanen:", football_clubs)
print(f"Jumlah akhir klub bola di dalam list: {len(football_clubs)}")